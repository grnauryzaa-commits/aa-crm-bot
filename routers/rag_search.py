def find_relevant_context(user_message: str, max_fragments: int = 3) -> str:
    """
    Ищет в канонической базе фрагменты, релевантные запросу пользователя.
    Возвращает строку с найденными текстами, разделёнными пустой строкой.
    Если ничего не найдено — возвращает пустую строку.
    """
    msg = user_message.lower()
    scores = {}

    # Считаем, сколько тегов каждого фрагмента встречается в запросе
    for key, tags in TOPIC_TAGS.items():
        score = sum(1 for tag in tags if tag in msg)
        if score > 0:
            scores[key] = score

    if not scores:
        return ""

    # Сортируем по убыванию релевантности
    top_keys = sorted(scores, key=lambda k: scores[k], reverse=True)[:max_fragments]

    fragments = []
    for key in top_keys:
        text = CANONICAL_DATABASE.get(key)
        if text:
            fragments.append(text)

    return "\n\n".join(fragments)