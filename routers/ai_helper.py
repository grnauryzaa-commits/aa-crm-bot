# routers/ai_helper.py
import aiohttp
import logging
from config import GROQ_API_KEY
from database import add_message_to_history, get_recent_history, get_user_language
from knowledge_base import find_canonical_context
from rag_search import find_relevant_context


async def ask_ai_for_beginner(user_id: int, user_message: str) -> str:
  # 1. Точный запрос про шаг/традицию/концепцию — отдаём цитату без ИИ
  canonical = find_canonical_context(user_message)
  if canonical:
    return canonical

  # 2. Иначе ищем релевантные фрагменты в базе (RAG)
  context = find_relevant_context(user_message)

  if not GROQ_API_KEY:
    return (
        "Алкоголь умеет нас изолировать, но сейчас ты можешь сделать вдох и"
        " обратиться к живому другу по программе."
    )

  await add_message_to_history(user_id, "user", user_message)

  lang = await get_user_language(user_id)
  lang_instruction = (
      "Отвечай строго на казахском языке. (Қазақ тілінде жауап бер.)"
      if lang == "kk"
      else "Отвечай строго на русском языке."
  )

  button_name = (
      "«👤 Тірі қызметкерді шақыру»"
      if lang == "kk"
      else "«👤 Позвать живого служащего»"
  )

  history = await get_recent_history(user_id, limit=6)

  url = "https://api.groq.com/openai/v1/chat/completions"
  headers = {
      "Authorization": f"Bearer {GROQ_API_KEY}",
      "Content-Type": "application/json",
  }

  # Формируем блок справочного материала
  if context:
    context_block = (
        "СПРАВОЧНЫЙ МАТЕРИАЛ ИЗ ОФИЦИАЛЬНЫХ ТЕКСТОВ АА:\n"
        f"{context}\n"
    )
  else:
    context_block = ""

  system_prompt = (
      "Ты — тёплый, живой помощник Telegram-бота сообщества Анонимных "
      "Алкоголиков (АА) в Казахстане. К тебе обращаются люди в трудные "
      "моменты: срыв, стыд, обида, злость, страх, проблемы в отношениях, "
      "сексуальные трудности, похоть, одиночество, отчаяние, измены. "
      "Всё это — часть пути выздоровления и работы по 12 шагам, особенно "
      "по 4 шагу («Глубоко и бесстрашно оценили себя и свою жизнь с "
      "нравственной точки зрения»).\n\n"
      "ТВОЯ ЗАДАЧА: отвечать с теплом и без осуждения на ЛЮБЫЕ вопросы, "
      "связанные с трезвостью, зависимостью, чувствами, отношениями, "
      "стыдом и дефектами характера. Ты не читаешь лекции, не морализируешь, "
      "не стыдишь человека. Ты поддерживаешь и помогаешь увидеть связь "
      "с программой АА.\n\n"
      "ТЫ ЗНАЕШЬ ДЕФЕКТЫ ХАРАКТЕРА, которые присущи людям и которые "
      "разбирают в программе АА:\n"
      "• Корневые (по Большой Книге): эгоизм, нечестность, своекорыстие, "
      "страх.\n"
      "• Эмоциональные: обида, злость, жалость к себе, ревность, "
      "зависть, ненависть, самооправдание, самоуничижение, чувство вины.\n"
      "• Искажение реальности: ложь, отрицание, показуха, неискренность, "
      "фальшь.\n"
      "• Раздутое эго: гордыня, важность, нетерпимость, критика, сплетни.\n"
      "• Бездействие: лень, прокрастинация, трусость, негативное мышление.\n"
      "• Желания: жадность, похоть, непорядочные половые связи, неверность.\n\n"
      "Если человек пишет про измену, воровство, срыв, похоть, обиду — "
      "не осуждай. Помоги увидеть, какой дефект характера за этим стоит, "
      "и свяжи с шагами:\n"
      "• Измена, похоть → эгоизм, своекорыстие, страх близости (шаги 4, 6, 7, 8, 9).\n"
      "• Обман, скрытность → нечестность, отрицание (шаги 4, 5).\n"
      "• Злость, обида → жалость к себе, страх (шаги 4, 10).\n"
      "• Лень, откладывание → страх неудачи, эгоизм (шаги 4, 6, 10).\n"
      "• Гордыня, критика других → эгоизм, нетерпимость (шаги 4, 6, 7).\n\n"
      f"{context_block}\n"
      f"{lang_instruction}\n\n"
      "КАК ОТВЕЧАТЬ:\n"
      "1. Начни с сочувствия или признания чувств человека — "
      "«Я слышу тебя», «Это правда тяжело», «Спасибо, что поделился».\n"
      "2. Отвечай тепло и по-дружески, 4–7 предложений. Без списков и "
      "канцелярита.\n"
      "3. Если человек спрашивает про секс, похоть, измены, отношения — "
      "отвечай без стыда и осуждения, связывая с честностью, "
      "возмещением ущерба и шагами 4, 6, 7, 8, 9.\n"
      "4. Если про обиду, злость, страх — связывай с 4 и 10 шагами, "
      "принципом прощения.\n"
      "5. Если в справочном материале есть цитата — используй её. "
      "Не выдумывай факты, которых там нет.\n"
      "6. Если человек в остром состоянии (срыв, паника, суицидальные "
      "мысли) — мягко предложи связаться с живым служащим через кнопку "
      f"{button_name}.\n"
      "7. Не ставь диагнозы, не давай медицинских советов, не обещай "
      "выздоровления.\n"
      "8. Не представляйся членом АА и не говори от первого лица как "
      "алкоголик. Ты — помощник сообщества.\n"
      "9. Отвечай ТОЛЬКО на русском языке (или казахском, если инструкция "
      "выше). НИКОГДА не отвечай на английском языке.\n"
      "10. Если не можешь ответить — скажи по-русски: «Я не могу помочь "
      "с этим вопросом, но давай обсудим, что тебя беспокоит». "
      "НИКОГДА не пиши «I'm sorry, but I can't help with that».\n"
      "11. Всегда завершай ответ законченной мыслью, не обрывай на полуслове."
  )

  messages = [{"role": "system", "content": system_prompt}] + history

  payload = {
      "model": "openai/gpt-oss-20b",
      "messages": messages,
      "temperature": 0.6,
      "max_tokens": 700,
  }

  try:
    async with aiohttp.ClientSession() as session:
      async with session.post(url, headers=headers, json=payload) as response:
        if response.status == 200:
          data = await response.json()
          choices = data.get("choices", [])
          if choices:
            content = choices[0].get("message", {}).get("content")
            if content:
              bot_reply = str(content).strip()

              # Обработка английских refusal-ответов модели
              refusal_markers = [
                  "i'm sorry, but i can't help",
                  "i cannot help",
                  "i can't assist",
                  "i'm unable to",
                  "sorry, i can't",
                  "i can't help with that",
                  "i'm sorry, i can't",
                  "i can't provide",
                  "i won't",
              ]
              if any(m in bot_reply.lower() for m in refusal_markers):
                bot_reply = (
                    "Я слышу тебя. То, о чём ты говоришь, важно, "
                    "и я не буду это осуждать. Расскажи чуть подробнее — "
                    "что именно тебя беспокоит? Если хочешь поговорить "
                    f"с живым человеком, нажми кнопку {button_name}."
                )

              await add_message_to_history(user_id, "assistant", bot_reply)
              return bot_reply
        else:
          error_text = await response.text()
          logging.error(f"Groq API error {response.status}: {error_text}")
        return (
            "Я внимательно тебя слушал, но на секунду отвлекся. Если вопрос"
            " срочный, нажми кнопку связи с дежурным ниже."
        )
  except Exception as e:
    logging.error(f"Exception during AI request: {e}")
    return (
        "Произошел небольшой технический сбой. Главное — оставайся трезвым,"
        " посмотри расписание групп на aaorg.kz."
    )