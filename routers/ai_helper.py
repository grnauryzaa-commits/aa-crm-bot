import os
import aiohttp

async def ask_ai_for_beginner(user_message: str) -> str:
    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        return "Алкоголь умеет нас изолировать, но сейчас ты можешь сделать вдох и обратиться к живому другу по программе."

    url = "https://api.groq.com/openai/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    
    system_prompt = (
        "Ты — опытный член сообщества Анонимных Алкоголиков (АА) в Казахстане, который сам прошел все 12 Шагов, "
        "12 Традиций и 12 Концепций обслуживания, обрел трезвость и теперь делится опытом с новичком.\n\n"
        "ПРАВИЛА ТВОЕЙ РАБОТЫ:\n"
        "1. Стиль: Говори грамотно, емко, тепло и бережно (как старший товарищ). Никогда не признавайся, что ты бот или нейросеть.\n"
        "2. Длина: Отвечай максимум в 3–5 предложениях.\n"
        "3. Язык: Строго поддерживай язык пользователя (русский или казахский).\n"
        "4. КАТЕГОРИЧЕСКИЕ КАНОНИЧЕСКИЕ ПРАВИЛА (Никогда не путай их местами!):\n"
        "   - 7-я Традиция: Каждая группа АА должна полностью содержать себя сама, отказываясь от посторонней помощи.\n"
        "   - 10-й Шаг: Продолжали самоанализ и, когда допускали ошибки, сразу признавали это.\n"
        "   - 4-я Традиция: Каждая группа должна быть независимой во всем, за исключением дел, затрагивающих другие группы или АА в целом.\n"
        "   - 12-й Шаг: Достигнув духовного просвещения в результате этих шагов, мы старались нести эту весть алкоголикам и применять эти принципы во всех наших делах.\n"
        "Если пользователь спрашивает про конкретный Шаг, Традицию или Концепцию, ты обязан называть их строго по официальной литературе АА, не допуская никаких искажений или подмены понятий.\n"
        "5. Контакты и сайты: Если спрашивают про группы или расписание, направляй строго на официальный сайт aaorg.kz (в раздел собраний). Никогда не выдумывай номера телефонов!"
    )

    payload = {
        "model": "openai/gpt-oss-20b",
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_message}
        ],
        "temperature": 0.1,  # Минимальная температура для абсолютной точности текстов
        "max_tokens": 800
    }

    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(url, headers=headers, json=payload) as response:
                if response.status == 200:
                    data = await response.json()
                    choices = data.get("choices", [])
                    if choices:
                        content = choices[0].get("message", {}).get("content")
                        if content:
                            return str(content).strip()
                
                error_body = await response.text()
                print(f"Groq API Error [{response.status}]: {error_body}")
                return "Загляни на официальный сайт aaorg.kz в раздел собраний, там найдешь актуальное расписание групп. Если нужна помощь, нажми кнопку связи с дежурным."
                
    except Exception as e:
        print(f"Exception during request: {e}")
        return "Произошел небольшой технический сбой. Главное — оставайся трезвым, посмотри расписание групп на aaorg.kz."