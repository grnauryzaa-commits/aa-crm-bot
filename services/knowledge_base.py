def find_canonical_context(user_message: str) -> str:
    """
    Безошибочный поиск канонического текста по всем 36 принципам АА 
    (Шаги, Традиции, Концепции) независимо от падежей и написания.
    """
    msg = user_message.lower().replace("-", " ").replace("‑", " ")
    
    num_mapping = {
        "1": ["1", "перв"], "2": ["2", "втор"], "3": ["3", "трет"],
        "4": ["4", "четвер"], "5": ["5", "пят"], "6": ["6", "шест"],
        "7": ["7", "седьм"], "8": ["8", "восьм"], "9": ["9", "девят"],
        "10": ["10", "десят"], "11": ["11", "одиннадцат"], "12": ["12", "двенадцат"]
    }
    
    target_type = None
    if "шаг" in msg or "шага" in msg or "шагу" in msg or "шаге" in msg:
        target_type = "шаг"
    elif "традиц" in msg:
        target_type = "традиция"
    elif "концепц" in msg:
        target_type = "концепция"

    found_num = None
    for num_str, variants in num_mapping.items():
        for v in variants:
            if v in msg:
                found_num = num_str
                break
        if found_num:
            break

    if target_type and found_num:
        key = f"{target_type} {found_num}"
        if key in CANONICAL_DATABASE:
            return CANONICAL_DATABASE[key]

    return ""