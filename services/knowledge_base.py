def find_canonical_context(user_message: str) -> str:
    """
    Универсальный поиск: распознает шаги, традиции или концепции
    в любых формулировках пользователя (например, «10 традиция», «десятая традиция», «шаг 3»).
    """
    msg = user_message.lower()
    
    # 1. Прямой поиск по ключам словаря (например, "шаг 1", "традиция 10", "концепция 5")
    for key, text in AA_CANON.items():
        parts = key.split()
        word = parts[0]     # шаг, традиция или концепция
        num = parts[1]      # номер
        
        if (f"{word} {num}" in msg) or (f"{num} {word}" in msg) or (f"{num}-й {word}" in msg) or (f"{num}ую {word}" in msg):
            return f"Канонический текст ({key.upper()}): «{text}»"

    # 2. Текстовый словарь для числительных (первая, десятая, третья и т.д.)
    num_words = {
        "1": "перв", "2": "втор", "3": "трет", "4": "четвер", "5": "пят", 
        "6": "шест", "7": "седьм", "8": "восьм", "9": "девят", "10": "десят", 
        "11": "одиннадцат", "12": "двенадцат"
    }
    
    for key, text in AA_CANON.items():
        w_type, w_num = key.split()
        rus_stem = num_words.get(w_num, "")
        
        if w_type in msg and (w_num in msg or (rus_stem and rus_stem in msg)):
            return f"Канонический текст ({key.upper()}): «{text}»"

    return ""