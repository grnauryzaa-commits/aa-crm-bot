def find_canonical_context(user_message: str) -> str:
    """
    Жесткий поиск по шагам, традициям и концепциям без путаницы.
    """
    import re
    msg = user_message.lower().replace("-", " ").replace("‑", " ")
    
    # 1. Точно определяем категорию по ключевым словам
    prefix = None
    if "шаг" in msg or "шага" in msg or "шаге" in msg:
        prefix = "шаг"
    elif "традиц" in msg:
        prefix = "традиция"
    elif "концепц" in msg:
        prefix = "концепция"

    # 2. Ищем число от 1 до 12 в тексте
    numbers = re.findall(r'\b(1[0-2]|[1-9])\b', msg)
    
    if numbers:
        num = numbers[0]
        
        # Если префикс явно указан в тексте — ищем строго по нему
        if prefix:
            key = f"{prefix} {num}"
            if key in CANONICAL_DATABASE:
                return CANONICAL_DATABASE[key]
        
        # Если префикс НЕ указан, но есть число, проверяем по приоритету: 
        # сначала смотрим традиции, если нет — концепции, если нет — шаги
        for p in ["традиция", "концепция", "шаг"]:
            key = f"{p} {num}"
            if key in CANONICAL_DATABASE:
                return CANONICAL_DATABASE[key]

    return ""