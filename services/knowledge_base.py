def find_canonical_context(user_message: str) -> str:
    msg_lower = user_message.lower()
    
    for i in range(1, 13):
        if f"{i} шаг" in msg_lower or f"шаг {i}" in msg_lower or f"шаг №{i}" in msg_lower:
            return AA_CANONICAL_DATA.get(f"step_{i}", "")
            
    if "7" in msg_lower and "традиц" in msg_lower:
        return AA_CANONICAL_DATA.get("tradition_7", "")
    if "4" in msg_lower and "традиц" in msg_lower:
        return AA_CANONICAL_DATA.get("tradition_4", "")
        
    return ""